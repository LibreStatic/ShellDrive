def check():
    for box in S:
        for row in box:
            assert sorted(row) == list(range(16))
    assert sorted(IP) == list(range(1, 65))
    assert sorted(P) == list(range(1, 33))
    assert sorted(PC2) == sorted(set(PC2)) and len(PC2) == 48 and max(PC2) == 56
    assert len(set(PC1)) == 56 and all(b % 8 for b in PC1)
    assert sum(SHIFTS) == 28
    # The selector construction in des3.c assumes this E table (box s takes R bits 4s .. 4s+5).
    for s in range(8):
        for j in range(6):
            assert E[6 * s + j] == (4 * s + j - 1) % 32 + 1


def main():
    check()
    o = sys.stdout
    o.write("/* Generated by des3_gen_tables.py from the tables of FIPS 46-3; do not edit. */\n\n")
    c = []
    for v in range(64):
        row = ((v >> 4) & 2) | (v & 1)
        col = (v >> 1) & 15
        w = 0
        for s in range(8):
            w |= S[s][row][col] << (28 - 4 * s)
        c.append(w)
    o.write("static const uint32_t k_des_mux[32][2] = {\n")
    for i in range(32):
        o.write("  { 0x%08xu, 0x%08xu },\n" % (c[2 * i], c[2 * i] ^ c[2 * i + 1]))
    o.write("};\n\n")
    # P: output bit i (1-based, MSB first) = input bit P[i]. Word bit numbers: 32 - position.
    groups = {}
    for i, src in enumerate(P):
        dst_bit = 31 - i
        src_bit = 32 - src
        groups.setdefault(dst_bit - src_bit, 0)
        groups[dst_bit - src_bit] |= 1 << dst_bit
    o.write("static SD_FORCEINLINE uint32_t des_perm_p(uint32_t x)\n{\n  return\n")
    terms = []
    for sh in sorted(groups):
        m = groups[sh]
        if sh > 0:
            terms.append("    ((x << %d) & 0x%08xu)" % (sh, m))
        elif sh < 0:
            terms.append("    ((x >> %d) & 0x%08xu)" % (-sh, m))
        else:
            terms.append("    (x & 0x%08xu)" % m)
    o.write(" |\n".join(terms) + ";\n}\n\n")

    def table(name, t):
        o.write("static const uint8_t %s[%d] = {" % (name, len(t)))
        for i, x in enumerate(t):
            o.write(("\n  " if i % 16 == 0 else " ") + "%d," % x)
        o.write("\n};\n\n")

    fp = [0] * 64
    for i, src in enumerate(IP):
        fp[src - 1] = i + 1
    table("k_des_ip", IP)
    table("k_des_fp", fp)
    table("k_des_pc1", PC1)
    table("k_des_pc2", PC2)
    table("k_des_shifts", SHIFTS)


main()
