"""Independent X25519 reference (RFC 7748 §5, Python big integers, our own code) used to produce
x25519_random.txt: random scalars and u-coordinates (including values >= p and with bit 255 set)
with the expected output. Run: python -I x25519_ref.py x25519_random.txt"""
import random
import sys

P = 2**255 - 19


def decode_u(b):
    b = bytearray(b)
    b[31] &= 127
    return int.from_bytes(b, "little")


def decode_scalar(b):
    b = bytearray(b)
    b[0] &= 248
    b[31] &= 127
    b[31] |= 64
    return int.from_bytes(b, "little")


def x25519(k, u):
    x1, x2, z2, x3, z3, swap = u, 1, 0, u, 1, 0
    for t in range(254, -1, -1):
        kt = (k >> t) & 1
        swap ^= kt
        if swap:
            x2, x3, z2, z3 = x3, x2, z3, z2
        swap = kt
        a = x2 + z2
        aa = a * a
        b = x2 - z2
        bb = b * b
        e = aa - bb
        c = x3 + z3
        d = x3 - z3
        da = d * a
        cb = c * b
        x3 = (da + cb) ** 2 % P
        z3 = u * (da - cb) ** 2 % P
        x2 = aa * bb % P
        z2 = e * (aa + 121665 * e) % P
    if swap:
        x2, z2 = x3, z3
    return x2 * pow(z2, P - 2, P) % P


def main():
    rnd = random.Random(20261024)
    with open(sys.argv[1], "w", encoding="ascii", newline="\n") as f:
        f.write("# scalar u expected (generated by x25519_ref.py, seed 20261024)\n")
        i = written = 0
        while written < 500:
            i += 1
            k = bytes(rnd.getrandbits(8) for _ in range(32))
            if i % 50 == 0:
                u = (P + rnd.randrange(19)).to_bytes(32, "little")          # non-canonical u
            else:
                u = bytes(rnd.getrandbits(8) for _ in range(32))            # bit 255 random too
            out = x25519(decode_scalar(k), decode_u(u))
            if out == 0:
                continue
            f.write("%s %s %s\n" % (k.hex(), u.hex(), out.to_bytes(32, "little").hex()))
            written += 1


if __name__ == "__main__":
    main()
