# Generates the SHA-2 constants of FIPS 180-4 section 4.2 and 5.3 (fractional parts of the square and
# cube roots of the first primes), in exact integer arithmetic. Run by hand: python -I gen_sha2_consts.py out.inc
import sys
def primes(n):
    out, k = [], 2
    while len(out) < n:
        if all(k % p for p in out):
            out.append(k)
        k += 1
    return out
def iroot(x, r):
    lo, hi = 0, 1 << (x.bit_length() // r + 2)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** r <= x: lo = mid
        else: hi = mid - 1
    return lo
def frac_root(p, r, bits):
    return iroot(p << (r * bits), r) & ((1 << bits) - 1)
P = primes(80)
k256 = [frac_root(p, 3, 32) for p in P[:64]]
h256 = [frac_root(p, 2, 32) for p in P[:8]]
k512 = [frac_root(p, 3, 64) for p in P[:80]]
h512 = [frac_root(p, 2, 64) for p in P[:8]]
h384 = [frac_root(p, 2, 64) for p in P[8:16]]
assert k256[0] == 0x428a2f98 and h256[0] == 0x6a09e667 and k512[79] == 0x6c44198c4a475817
assert h384[0] == 0xcbbb9d5dc1059ed8
def arr(name, t, vals, fmt, per):
    s = ["static const %s %s[%d] = {" % (t, name, len(vals))]
    for i in range(0, len(vals), per):
        s.append("  " + ", ".join(fmt % v for v in vals[i:i+per]) + ",")
    s.append("};")
    return "\n".join(s)
out = ["/* Generated by gen_sha2_consts.py (FIPS 180-4 constants computed from prime roots). Data, not code. */",
       arr("k_sha256_k", "uint32_t", k256, "0x%08xu", 6),
       arr("k_sha256_iv", "uint32_t", h256, "0x%08xu", 4),
       arr("k_sha512_k", "uint64_t", k512, "0x%016xull", 3),
       arr("k_sha512_iv", "uint64_t", h512, "0x%016xull", 3),
       arr("k_sha384_iv", "uint64_t", h384, "0x%016xull", 3)]
open(sys.argv[1], "w", newline="\n").write("\n".join(out) + "\n")
