# Generates the Blowfish initial state: the fractional hex digits of pi (Schneier 1993), computed
# here with Machin's formula in exact integer arithmetic.
import sys
WORDS = 18 + 4 * 256
BITS = WORDS * 32 + 128
ONE = 1 << BITS
def atan_inv(x):
    s, t, n, sign = 0, ONE // x, 1, 1
    x2 = x * x
    while t:
        s += sign * (t // n)
        t //= x2
        n += 2
        sign = -sign
    return s
pi = 16 * atan_inv(5) - 4 * atan_inv(239)
frac = pi - 3 * ONE
words = []
for i in range(WORDS):
    frac <<= 32
    w = frac >> BITS
    frac &= ONE - 1
    words.append(w)
assert words[0] == 0x243F6A88 and words[1] == 0x85A308D3
out = []
out.append("/* Generated by gen_blowfish_pi.py (run by hand) from Machin's formula: the first %d 32-bit words of the" % WORDS)
out.append(" * fractional part of pi in hexadecimal, the Blowfish initial P-array (18 words) followed by the")
out.append(" * four S-boxes (256 words each), as defined by the Blowfish specification. Data, not code. */")
out.append("static const uint32_t k_blf_pi[%d] = {" % WORDS)
for i in range(0, WORDS, 6):
    out.append("  " + ", ".join("0x%08xu" % w for w in words[i:i+6]) + ",")
out.append("};")
open(sys.argv[1], "w", newline="\n").write("\n".join(out) + "\n")
