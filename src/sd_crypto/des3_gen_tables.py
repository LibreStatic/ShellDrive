# Generates des3_tables.inc for des3.c from the DES tables of FIPS 46-3 (also SP 800-67 Rev. 2,
# section 3), typed in from the standard. Run by hand: python -I des3_gen_tables.py > des3_tables.inc
# Outputs:
#   k_des_mux[32][2]: multiplexer constants for the boolean S-box network. For a 6-bit S-box input
#     v = b1 b2 b3 b4 b5 b6 (b1 most significant), C[v] holds S_s(v) in nibble s (box 1 in the top
#     nibble) of a 32-bit word, i.e. the pre-P layout of FIPS 46-3. The table stores C[2i] and
#     C[2i] ^ C[2i+1] (the first network level selects on b6). Indexed by public i only.
#   des_perm_p(): the P permutation as grouped shift-and-mask terms.
#   k_des_ip, k_des_fp, k_des_pc1, k_des_pc2, k_des_shifts.
